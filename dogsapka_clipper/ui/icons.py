def svg(name: str, color: str = "#ECECF4", stroke: float = 2.0) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{PATHS.get(name, "")}</svg>')


@lru_cache(maxsize=256)
def pixmap(name: str, color: str = "#ECECF4", size: int = 18) -> QPixmap:
    r = QSvgRenderer(QByteArray(svg(name, color).encode()))
    pm = QPixmap(size * 2, size * 2)
    pm.fill(Qt.transparent)
    p = QPainter(pm)
    r.render(p, QRectF(0, 0, size * 2, size * 2))
    p.end()
    pm.setDevicePixelRatio(2.0)
    return pm


def icon(name: str, color: str = "#ECECF4", size: int = 18) -> QIcon:
    ic = QIcon(pixmap(name, color, size))
    return ic


def app_icon() -> QIcon:
    """Gradient play/scissors logo drawn at runtime (also exported as .ico for packaging)."""
    from PySide6.QtGui import QColor, QLinearGradient, QPainterPath, QPen
    ic = QIcon()
    for s in (16, 24, 32, 48, 64, 128, 256, 512, 1024):
        pm = QPixmap(s, s)
        pm.fill(Qt.transparent)
        p = QPainter(pm)
        p.setRenderHint(QPainter.Antialiasing)
        g = QLinearGradient(0, 0, s, s)
        g.setColorAt(0, QColor("#8B5CF6"))
        g.setColorAt(1, QColor("#22D3EE"))
        p.setBrush(g)
        p.setPen(Qt.NoPen)
        p.drawRoundedRect(QRectF(0, 0, s, s), s * 0.24, s * 0.24)
        path = QPainterPath()
        path.moveTo(s * 0.38, s * 0.28)
        path.lineTo(s * 0.74, s * 0.5)
        path.lineTo(s * 0.38, s * 0.72)
        path.closeSubpath()
        p.setBrush(QColor("white"))
        p.drawPath(path)
        p.setPen(QPen(QColor(255, 255, 255, 200), max(1.0, s * 0.05)))
        p.drawLine(int(s * 0.22), int(s * 0.82), int(s * 0.8), int(s * 0.82))
        p.end()
        ic.addPixmap(pm)
    return ic
